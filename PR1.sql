--CALCULATE TOTAL REVENUE GENERATED FROM ALL ORDER USING SUM()
SELECT SUM(Sub_Total)
FROM OrderDetails;	

--RETRIVE TOP 3 MOST ORDERED PRODUCTS
SELECT ProductID,SUM(Quantity) AS TotalQty
FROM OrderDetails
GROUP BY ProductID
ORDER BY TotalQty DESC
LIMIT 3;

--COUNT HOW MANY TIME SPECIFIC PRODUCT HAS BEEN SOLD USING COUT
