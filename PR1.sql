--RETRIVE HIGHEST,LOWEST,AND AVERAGE ORDER AMOUNT USING AGGREGATE FUNCTIONS
SELECT  
MAX(TotalAmount)AS HighestAmount,
MIN(TotalAmount)AS LowestAmount,
AVG(TotalAmount )AS AverageAmount
FROM Orders;

