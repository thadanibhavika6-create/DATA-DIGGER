--CREATE ORDER TABLE
CREATE TABLE Orders(
OrderID INT PRIMARY KEY,
CustomerID INT ,
OrderDate DATE,
TotalAmount DECIMAL(10,2),
FOREIGN KEY (CustomerID) REFERENCES
customers(CustomerID)
);

